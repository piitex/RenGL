    private static void segment(ByteArrayOutputStream out, int classAndId, int[] bits, int[] vals) {
        int length = 2 + 1 + 16 + vals.length;
        out.write(0xFF);
        out.write(0xC4);
        out.write(length >> 8);
        out.write(length);
        out.write(classAndId);
        for (int b : bits) out.write(b);
        for (int v : vals) out.write(v);
    }
